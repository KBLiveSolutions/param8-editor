import * as esbuild from "esbuild";
import * as fs from "node:fs";
import * as path from "node:path";

const manifest = JSON.parse(fs.readFileSync("manifest.json", "utf8"));
const production = process.argv.includes("--production");

// Embed editor/public files into src/assets.ts
const PUBLIC_DIR = path.resolve("../editor/public");
const MIME_MAP: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js":   "application/javascript; charset=utf-8",
  ".css":  "text/css; charset=utf-8",
  ".json": "application/json",
  ".svg":  "image/svg+xml",
};
const files = fs.readdirSync(PUBLIC_DIR)
  .filter(f => !f.startsWith(".") && fs.statSync(path.join(PUBLIC_DIR, f)).isFile());
const entries = files.map(f => {
  const ext = path.extname(f);
  const mime = MIME_MAP[ext] ?? "application/octet-stream";
  const b64 = fs.readFileSync(path.join(PUBLIC_DIR, f)).toString("base64");
  return `  "/${f}": { data: Buffer.from("${b64}", "base64"), mime: "${mime}" }`;
});
fs.writeFileSync(
  "src/assets.ts",
  `// Auto-generated by build.ts – do not edit\nexport const STATIC_FILES: Record<string, { data: Buffer; mime: string }> = {\n${entries.join(",\n")}\n};\n`,
);

await esbuild.build({
  entryPoints: ["src/extension.ts"],
  outfile: manifest.entry,
  bundle: true,
  format: "cjs",
  platform: "node",
  sourcesContent: false,
  logLevel: "info",
  minify: production,
  sourcemap: !production,
  loader: { ".html": "text" },
});
